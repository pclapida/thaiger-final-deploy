drop policy if exists "Admins editan la configuración" on public.settings;
create policy "Admins editan la configuración" on public.settings
    for all using (public.is_admin()) with check (public.is_admin());

insert into public.settings (id, value)
values ('site', '{}'::jsonb)
on conflict (id) do nothing;

-- ------------------------------------------------------- INVENTARIO (RPC)
create or replace function public.decrement_stock(product_id bigint, qty integer)
returns void
language sql
security definer
set search_path = public
as $$
    update public.products
       set stock = greatest(0, stock - qty)
     where id = product_id;
$$;

